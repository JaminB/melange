# Builds erg-mcp into tools\erg-mcp\dist\erg-mcp.mjs with the portable toolchain in tools\ (scripts\web\fetch.ps1):
# lists the tool groups (every src\tools\*.ts) in src\tools\groups.gen.ts, type-checks with the web app's TypeScript,
# then bundles with esbuild for Node. Usage: .\tools\erg-mcp\build.ps1 [-SkipTypeCheck] [-IfStale]
# -IfStale builds only when dist\erg-mcp.mjs is missing or older than a source it bundles (src\ and the editor's modules
# under web\src), so the launcher and the bench never run a stale bundle.
param([switch]$SkipTypeCheck, [switch]$IfStale)
$ErrorActionPreference = "Stop"
$here = $PSScriptRoot
$root = Split-Path (Split-Path $here -Parent) -Parent
$node = Join-Path $root "tools\node\node.exe"
$esbuild = Join-Path $root "tools\esbuild\esbuild.exe"
$tsc = Join-Path $root "web\node_modules\typescript\bin\tsc"
foreach ($f in @($node, $esbuild)) { if (-not (Test-Path $f)) { throw "missing $f; run scripts\web\fetch.ps1 first" } }

if ($IfStale) {
    $bundle = Join-Path $here "dist\erg-mcp.mjs"
    if (Test-Path $bundle) {
        $built = (Get-Item $bundle).LastWriteTimeUtc
        $newer = Get-ChildItem -Recurse -File -Include *.ts, *.mjs -Path (Join-Path $here "src"), (Join-Path $root "web\src\sdk"), (Join-Path $root "web\src\panels\erg") |
            Where-Object { $_.Name -ne "groups.gen.ts" -and $_.LastWriteTimeUtc -gt $built } | Select-Object -First 1
        if (-not $newer) { return }
        Write-Host "erg-mcp: $($newer.FullName) is newer than the bundle; rebuilding"
    }
}

# Tool groups: one module per file, registered in file-name order.
$groups = @(Get-ChildItem (Join-Path $here "src\tools") -Filter *.ts | Where-Object { $_.Name -notmatch '\.gen\.ts$|\.d\.ts$' } |
    Sort-Object Name | ForEach-Object { $_.BaseName })
foreach ($g in $groups) { if ($g -notmatch '^[a-z][a-z0-9_]*$') { throw "tool group file '$g.ts' must be named [a-z][a-z0-9_]*" } }
$gen = @("// Generated by tools/erg-mcp/build.ps1 from the files in src/tools/: do not edit, and do not commit.")
$gen += $groups | ForEach-Object { "import * as $_ from `"./$_`";" }
$gen += ""
$gen += "export const GROUPS: [string, { tools: import(`"../registry`").Tool[] }][] = ["
$gen += $groups | ForEach-Object { "  [`"$_`", $_]," }
$gen += "];"
$genFile = Join-Path $here "src\tools\groups.gen.ts"
$text = ($gen -join "`n") + "`n"
if (-not (Test-Path $genFile) -or [IO.File]::ReadAllText($genFile) -ne $text) {
    [IO.File]::WriteAllText($genFile, $text, (New-Object Text.UTF8Encoding $false))
}

if (-not $SkipTypeCheck) {
    if (-not (Test-Path $tsc)) { throw "missing $tsc; run scripts\web\fetch.ps1 first" }
    & $node $tsc --noEmit -p (Join-Path $here "tsconfig.json")
    if ($LASTEXITCODE) { throw "tsc failed (erg-mcp)" }
}

$dist = Join-Path $here "dist"
New-Item -ItemType Directory -Force $dist | Out-Null
$out = Join-Path $dist "erg-mcp.mjs"
# three and preact stay external so a module that pulls in the editor's view or UI shows up below instead of being bundled.
& $esbuild (Join-Path $here "src\main.ts") --bundle --platform=node --format=esm --target=node22 --charset=utf8 `
    --legal-comments=none --external:three --external:preact --external:preact/* "--outfile=$out" --log-level=warning
if ($LASTEXITCODE) { throw "esbuild failed (erg-mcp)" }
if (Select-String -Path $out -Pattern 'from\s*"(three|preact)' -Quiet) {
    throw "erg-mcp imports three or preact: a tool reached past the editor's pure modules (see src/core.ts)"
}
Write-Host "erg-mcp: $($groups.Count) tool group(s) ($($groups -join ', ')), $([math]::Round((Get-Item $out).Length / 1024, 1)) KB -> $out"
