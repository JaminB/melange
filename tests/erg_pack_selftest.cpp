int g_fail = 0, g_pass = 0;

void Expect(bool ok, const std::string& what) {
    if (ok) {
        ++g_pass;
    } else {
        ++g_fail;
        printf("FAIL: %s\n", what.c_str());
    }
}

erg::Scene BareScene(const std::string& stem) {
    erg::Scene s;
    s.stem = stem;
    s.title = "Test";
    s.base = {"Multi.DinerMight", "game", "Multi_DinerMight", {std::string(64, 'a'), std::string(64, 'b'), std::string(64, 'c')}};
    erg::Frame root;
    root.id = 1;
    root.name = "root";
    s.frames.push_back(root);
    return s;
}

void AddWorm(erg::Scene& s, int i, erg::Vec3 pos) {
    erg::Detail d;
    d.id = 100 + i;
    d.frame = 1;
    d.name = "WORM" + std::to_string(i);
    d.resource = "CheesyGrinWorm";
    d.pos = pos;
    d.role = erg::Role::Spawn;
    s.details.push_back(d);
}

void AddNamed(erg::Scene& s, int64_t id, const char* name, const char* resource) {
    erg::Detail d;
    d.id = id;
    d.frame = 1;
    d.name = name;
    d.resource = resource;
    s.details.push_back(d);
}

// ---- luagen ----------------------------------------------------------------------------------------------------

void TestLuagenEmpty() {
    erg::Scene s = BareScene("demo_empty");
    Expect(!erg::luagen::Needed(s), "an empty scene needs no chunk");
    Expect(erg::luagen::Chunk(s).empty(), "an empty scene's chunk is empty text");
}

void TestLuagenWaterOnly() {
    erg::Scene s = BareScene("demo_water");
    s.water = 40.0;
    Expect(erg::luagen::Needed(s), "a water level needs a chunk");
    const std::string want = "-- generated by Erg for demo_water; edits are overwritten on export\n"
                              "SetData(\"Water.Level\", 40.0000)\n";
    Expect(erg::luagen::Chunk(s) == want, "water-only chunk has just the top-level SetData");
}

void TestLuagenKnotsOnly() {
    erg::Scene s = BareScene("demo_knots");
    s.spawns = erg::SpawnMode::Knots;
    for (int i = 0; i < 8; ++i) AddWorm(s, i, {0, 0, 0});
    const std::string want = "-- generated by Erg for demo_knots; edits are overwritten on export\n"
                              "local ergInit = Initialise\n"
                              "function Initialise()\n"
                              "    local ergSetup = lib_SetupMultiplayerWormsAndTeams\n"
                              "    lib_SetupMultiplayerWormsAndTeams = function()\n"
                              "        ergSetup()\n"
                              "        for i = 0, 7 do\n"
                              "            local lock, worm = EditContainer(lib_GetWormContainerName(i))\n"
                              "            worm.Spawn = \"WORM\" .. i\n"
                              "            CloseContainer(lock)\n"
                              "        end\n"
                              "    end\n"
                              "    ergInit()\n"
                              "    lib_SetupMultiplayerWormsAndTeams = ergSetup\n"
                              "end\n";
    Expect(erg::luagen::Chunk(s) == want, "knots-only chunk has just the loop, no water or PlaceObjects lines");
}

// Knots, two placed objects and a water level together.
void TestLuagenFull() {
    erg::Scene s = BareScene("mymaps_harbour");
    s.title = "Harbour Brawl";
    s.spawns = erg::SpawnMode::Knots;
    s.water = 40.0;
    for (int i = 0; i < 8; ++i) AddWorm(s, i, {0, 0, 0});
    AddNamed(s, 200, "oildrum", "OilDrum");
    AddNamed(s, 201, "mine", "Mine");
    Expect(erg::luagen::Needed(s), "knots + objects + water needs a chunk");
    const std::string want = "-- generated by Erg for mymaps_harbour; edits are overwritten on export\n"
                              "SetData(\"Water.Level\", 40.0000)\n"
                              "local ergInit = Initialise\n"
                              "function Initialise()\n"
                              "    local ergSetup = lib_SetupMultiplayerWormsAndTeams\n"
                              "    lib_SetupMultiplayerWormsAndTeams = function()\n"
                              "        ergSetup()\n"
                              "        for i = 0, 7 do\n"
                              "            local lock, worm = EditContainer(lib_GetWormContainerName(i))\n"
                              "            worm.Spawn = \"WORM\" .. i\n"
                              "            CloseContainer(lock)\n"
                              "        end\n"
                              "        SendMessage(\"GameLogic.PlaceObjects\")\n"
                              "        SetData(\"Water.Level\", 40.0000)\n"
                              "    end\n"
                              "    ergInit()\n"
                              "    lib_SetupMultiplayerWormsAndTeams = ergSetup\n"
                              "end\n";
    Expect(erg::luagen::Chunk(s) == want, "the full chunk matches the expected text byte for byte");
    const std::string legacy = "-- generated by Erg for mymaps_harbour; edits are overwritten on export\n"
                                "SetData(\"Water.Level\", 40.0000)\n"
                                "local ergSetup = lib_SetupMultiplayerWormsAndTeams\n"
                                "function lib_SetupMultiplayerWormsAndTeams()\n"
                                "    ergSetup()\n"
                                "    for i = 0, 7 do\n"
                                "        local lock, worm = EditContainer(lib_GetWormContainerName(i))\n"
                                "        worm.Spawn = \"WORM\" .. i\n"
                                "        CloseContainer(lock)\n"
                                "    end\n"
                                "    SendMessage(\"GameLogic.PlaceObjects\")\n"
                                "    SetData(\"Water.Level\", 40.0000)\n"
                                "end\n";
    std::string run, why;
    Expect(!erg::luagen::IsGenerated(s.stem, legacy, &why) && why.find("older Erg") != std::string::npos,
           "a v1 chunk is not the current form");
    Expect(erg::luagen::Upgrade(s.stem, legacy, &run, &why) && run == want, "a v1 chunk is upgraded to the deferred form on load");
}

