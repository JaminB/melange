std::wstring Widen(const std::string& s) { return std::wstring(s.begin(), s.end()); }

void TestPackScript(const fs::path& base) {
    const std::string text = "wum.log('hello from ' .. wum.level.stem)\n";
    for (bool source : {false, true}) {
        const fs::path dir = base / (source ? "script-source" : "script-install") / "erg-pack-test";
        auto spec = BasicSpec("sample", source, false);
        spec.script = text;
        std::vector<std::string> files;
        std::string err;
        Expect(erg::pack::WritePack(spec, dir.wstring(), &files, &err), "an export with a script succeeds: " + err);
        Expect(ReadFile(dir / "sim" / "sample.lua") == text, "the script is copied to sim/<slug>.lua");
        Expect(std::find(files.begin(), files.end(), "sim/sample.lua") != files.end(), "the written files list the script");
        melange::spice::Manifest m;
        std::vector<melange::spice::Error> errs;
        std::vector<melange::levels::manifest::Error> lerrs;
        const bool parsed = melange::spice::Parse(dir.wstring(), &m, &errs);
        const auto decls = parsed ? melange::levels::manifest::Parse(m, &lerrs) : std::vector<melange::levels::manifest::LevelDecl>{};
        Expect(decls.size() == 1 && decls[0].sim == "sim/sample.lua",
               "spice.json declares levels[].sim" + (errs.empty() ? std::string() : ": " + errs.front().text) +
                   (lerrs.empty() ? std::string() : ": " + lerrs.front().text));
        Expect(erg::pack::WritePack(BasicSpec("sample", source, false), dir.wstring(), &files, &err) &&
                   !FileExists(dir / "sim" / "sample.lua") && ReadFile(dir / "spice.json").find("\"sim\"") == std::string::npos,
               "a re-export without a script removes it: " + err);
    }
    auto bad = BasicSpec("sample", true, false);
    bad.script = std::string("\x1bLua", 4);
    std::vector<std::string> files;
    std::string err;
    Expect(!erg::pack::WritePack(bad, (base / "script-bad").wstring(), &files, &err) && !FileExists(base / "script-bad" / "spice.json"),
           "compiled Lua is refused before anything is written");
}

void TestSampleModParses() {
    const std::wstring dir = Widen(std::string(MELANGE_SOURCE_DIR) + "/dist/Mods/erg-sample");
    melange::spice::Manifest m;
    std::vector<melange::spice::Error> errs;
    const bool ok = melange::spice::Parse(dir, &m, &errs);
    std::string why;
    for (auto& e : errs) why += e.field + ": " + e.text + "; ";
    Expect(ok, "dist/Mods/erg-sample/spice.json parses: " + why);
    if (!ok) return;
    Expect(m.id == "erg-sample", "the sample's id matches its folder name");
    Expect(m.content, "the sample is a content mod");
    Expect(!m.defaultEnabled, "the sample ships disabled");
    Expect(m.levels.size() == 1, "the sample declares exactly one level");
    if (m.levels.size() != 1) return;
    Expect(m.levels[0].slug == "sample", "the level's slug is 'sample'");
    Expect(m.levels[0].chunk, "the level needs a generated chunk (knots + water)");
    Expect(m.levels[0].source == "src/sample.ergpatch.json", "the level names its patch as its source");

    std::vector<lm::Error> lerrs;
    const auto decls = lm::Parse(m, &lerrs);
    Expect(decls.size() == 1 && lerrs.empty(), "the manifest's levels array is accepted by levels::manifest::Parse");
    if (decls.size() == 1) {
        Expect(decls[0].stem == "erg_sample_sample", "the level's stem is erg_sample_sample");
        std::string stemErr;
        Expect(erg::names::ValidStem(decls[0].stem, "erg_sample", &stemErr), "the stem is a valid, non-vanilla stem: " + stemErr);
    }

    const std::string patchText = ReadFile(fs::path(dir) / "src" / "sample.ergpatch.json");
    erg::Patch p;
    std::string perr;
    Expect(erg::ParsePatch(patchText, &p, &perr), "the sample's patch parses: " + perr);
    Expect(p.spawns == erg::SpawnMode::Knots, "the sample uses knot spawns");
    Expect(p.water.has_value() && *p.water == 25.0, "the sample sets water to 25");
    size_t sets = 0, drums = 0, mines = 0, voxels = 0;
    for (auto& op : p.ops) {
        if (op.kind == erg::Op::Kind::Set && op.src >= 1) ++sets;
        if (op.kind == erg::Op::Kind::Add && op.fields.name && *op.fields.name == "oildrum") ++drums;
        if (op.kind == erg::Op::Kind::Add && op.fields.name && *op.fields.name == "mine") ++mines;
        if (op.kind == erg::Op::Kind::Voxels) ++voxels;
    }
    Expect(sets == 8, "the sample moves the 8 knots");
    Expect(drums == 3 && mines == 2, "the sample places 3 drums and 2 mines");
    Expect(voxels > 0 && sets + drums + mines + voxels == p.ops.size(), "the sample carves a little terrain and does nothing else");
}

void TestPackNeverWritesCshEvenIfAskedTwice(const fs::path& base) {
    // Re-running an install export must not resurrect a .csh a previous (buggy) caller left behind.
    const fs::path dir = base / "csh";
    std::string err;
    std::vector<std::string> files;
    Expect(erg::pack::WritePack(BasicSpec("sample", false, true), dir.wstring(), &files, &err), "export ok: " + err);
    for (auto& f : files) Expect(f.size() < 4 || f.substr(f.size() - 4) != ".csh", "no returned file is a .csh: " + f);
}
